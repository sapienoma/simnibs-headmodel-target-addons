"""Recompute EEG using installed SimNIBS official CLI on a reviewed repaired surface.
Runs in SimNIBS's ORIGINAL Python environment, never repair's private dependencies.
"""
import argparse,csv,hashlib,importlib.util,json,os,subprocess,sys,time
from pathlib import Path
import numpy as np
from surface_cleanup import clean_surface
FIDUCIALS=('Nz','Iz','LPA','RPA')
def digest(path):
 h=hashlib.sha256()
 with open(path,'rb') as f:
  for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
 return h.hexdigest()
def read_positions(path,audit=None):
 groups={};points={}
 with open(path,encoding='utf-8-sig',newline='') as f:
  for line,row in enumerate(csv.reader(f),1):
   if len(row)<5:continue
   kind=row[0].strip()
   if kind not in ('Electrode','ReferenceElectrode','Fiducial','Generic'):continue
   name=row[4].strip()
   if not name:continue
   p=np.array(row[1:4],float)
   if not np.isfinite(p).all():raise ValueError('Non-finite coordinate: '+name)
   groups.setdefault(name,[]).append((kind,p,line))
 for name,rows in groups.items():
  # SimNIBS caps may contain Iz both as Electrode and Fiducial.
  fid=[r for r in rows if r[0]=='Fiducial']
  chosen=fid if name in FIDUCIALS and fid else rows
  first=chosen[0]
  for row in chosen[1:]:
   if not np.allclose(row[1],first[1],rtol=0,atol=1e-4):
    raise ValueError(f'Conflicting CSV point {name} at row {first[2]} {first[1].tolist()} versus row {row[2]} {row[1].tolist()}. Review and keep the correct coordinates.')
  points[name]=first[1]
  if len(rows)>1:
   entry={'name':name,'selected_type':first[0],'selected_line':first[2],'rows':[{'type':r[0],'line':r[2],'RAS_mm':r[1].tolist()} for r in rows]}
   if audit is not None:audit.append(entry)
   print(f'Duplicate CSV marker {name}: using {first[0]} row {first[2]} (Fiducial rows take priority for the four landmarks; conflicting coordinates of equal priority are rejected).',flush=True)
 return points

def read_ply(path):
 with open(path,encoding='ascii') as f:
  if f.readline().strip()!='ply' or f.readline().strip()!='format ascii 1.0':raise ValueError('Expected the ASCII PLY generated by this tool')
  nv=nf=None
  for line in f:
   if line.startswith('element vertex '):nv=int(line.split()[-1])
   if line.startswith('element face '):nf=int(line.split()[-1])
   if line.strip()=='end_header':break
  if not nv or not nf:raise ValueError('Empty surface')
  v=np.array([list(map(float,f.readline().split())) for _ in range(nv)])
  raw=np.array([list(map(int,f.readline().split())) for _ in range(nf)])
 if v.shape!=(nv,3) or raw.shape!=(nf,4) or not np.all(raw[:,0]==3):raise ValueError('Unexpected surface layout')
 tri=raw[:,1:]
 if tri.min()<0 or tri.max()>=nv or not np.isfinite(v).all():raise ValueError('Invalid surface')
 return v,tri

def project(v,tri,p):
 a,b,c=v[tri[:,0]],v[tri[:,1]],v[tri[:,2]];ab=b-a;ac=c-a;ap=p-a
 aa=(ab*ab).sum(1);bb=(ab*ac).sum(1);cc=(ac*ac).sum(1);dd=(ap*ab).sum(1);ee=(ap*ac).sum(1);den=aa*cc-bb*bb
 good=den>1e-14;u=np.zeros(len(den));w=u.copy();u[good]=(dd*cc-ee*bb)[good]/den[good];w[good]=(ee*aa-dd*bb)[good]/den[good]
 q=a+u[:,None]*ab+w[:,None]*ac;valid=good&(u>=0)&(w>=0)&(u+w<=1);dist=((q-p)**2).sum(1);dist[~valid]=np.inf;i=dist.argmin();best=(float(dist[i]),q[i])
 for x,y in [(a,b),(b,c),(c,a)]:
  e=y-x;den=(e*e).sum(1);valid=den>1e-14;z=np.zeros(len(den));z[valid]=np.clip(((p-x)*e).sum(1)[valid]/den[valid],0,1);q=x+z[:,None]*e;dist=((q-p)**2).sum(1);dist[~valid]=np.inf;i=dist.argmin()
  if dist[i]<best[0]:best=(float(dist[i]),q[i])
 return best[1],float(np.sqrt(best[0]))

def boundary_vertices(v,tri):
 edges=np.sort(np.vstack([tri[:,[0,1]],tri[:,[1,2]],tri[:,[2,0]]]),axis=1);unique,count=np.unique(edges,axis=0,return_counts=True)
 if np.any(count>2):raise ValueError('Surface has non-manifold edges; edit/rebuild the mask')
 return v[np.unique(unique[count==1])]

def write_msh(path,v,tri):
 # Normalize global orientation to outward; needed by SimNIBS surface projection.
 a,b,c=v[tri[:,0]],v[tri[:,1]],v[tri[:,2]]
 if np.sum(np.einsum('ij,ij->i',np.cross(b-a,c-a),(a+b+c)/3-v.mean(0)))<0:tri=tri[:,::-1]
 with open(path,'w',encoding='ascii') as f:
  f.write('$MeshFormat\n2.2 0 8\n$EndMeshFormat\n$Nodes\n'+str(len(v))+'\n')
  for i,p in enumerate(v,1):f.write(f'{i} {p[0]:.8f} {p[1]:.8f} {p[2]:.8f}\n')
  f.write('$EndNodes\n$Elements\n'+str(len(tri))+'\n')
  for i,t in enumerate(tri+1,1):f.write(f'{i} 2 2 1005 1005 {t[0]} {t[1]} {t[2]}\n')
  f.write('$EndElements\n')

def run(work,fidcsv):
 work=Path(work);manifest=json.loads((work/'manifest.json').read_text(encoding='utf-8'));review=manifest.get('user_review')
 if not review:raise ValueError('Review and export the REVIEWED scalp surface first.')
 mask=work/'scalp_envelope_REVIEWED.nii.gz';ply=work/'scalp_surface_REVIEWED_RAS.ply'
 if not mask.is_file() or digest(mask)!=review.get('mask_sha256'):raise ValueError('Reviewed mask changed; export the reviewed surface again')
 # Older v0.1 exports did not hash the PLY: require re-export, never silently trust it.
 if not ply.is_file() or digest(ply)!=review.get('surface_sha256'):raise ValueError('Re-export the reviewed surface with the updated tool to record the matching surface and mask.')
 duplicate_audit=[];points=read_positions(fidcsv,duplicate_audit)
 for name in FIDUCIALS:
  if name not in points:raise ValueError('CSV missing fiducial: '+name)
 if np.linalg.norm(points['LPA']-points['RPA'])<50 or np.linalg.norm(points['Nz']-points['Iz'])<80:raise ValueError('Implausible fiducial spacing; verify coordinates are in mm.')
 v,tri=read_ply(ply);v,tri,cleanup=clean_surface(v,tri)
 print('Surface validation / cleanup: '+json.dumps(cleanup,ensure_ascii=False),flush=True)
 boundary=boundary_vertices(v,tri);projected={};offsets={}
 for name in FIDUCIALS:
  q,d=project(v,tri,points[name])
  if d>5:raise ValueError(f'{name} surface distance: {d:.2f} mm exceeds 5 mm. Check subject, RAS coordinates and scalp contour.')
  if len(boundary) and np.linalg.norm(boundary-q,axis=1).min()<5:raise ValueError(f'{name} is too close to an open surface boundary for reliable EEG recomputation.')
  projected[name]=q;offsets[name]=d
 try:available=importlib.util.find_spec('simnibs.cli.eeg_positions') is not None
 except ModuleNotFoundError:available=False
 if not available:raise ValueError('SimNIBS eeg_positions was not found. Start this tool using the installed SimNIBS 4.6 Python.')
 out=work/('EEG_recomputed_'+time.strftime('%Y%m%d_%H%M%S'));out.mkdir(exist_ok=False)
 mesh=out/'scalp_surface_ONLY.msh';write_msh(mesh,v,tri)
 prefix=out/'EEG10-10_recomputed';args=[sys.executable,'-u','-m','simnibs.cli.eeg_positions','-m',str(mesh),'-o',str(prefix)]
 for name in FIDUCIALS:args+=['-'+name]+[str(float(x)) for x in projected[name]]
 print('Running SimNIBS EEG 10-10 recomputation. This surface-only MSH is not a volume FEM.',flush=True)
 record={'status':'RUNNING','source_manifest_sha256':digest(work/'manifest.json'),'surface_sha256':digest(ply),'surface_cleanup':cleanup,'fiducial_csv':str(Path(fidcsv).resolve()),'fiducial_csv_sha256':digest(fidcsv),'duplicate_point_resolution':duplicate_audit,'fiducials_input_RAS_mm':{k:points[k].tolist() for k in FIDUCIALS},'fiducials_projected_RAS_mm':{k:projected[k].tolist() for k in FIDUCIALS},'projection_offset_mm':offsets,'command':args,'FEM':False}
 def write(): (out/'eeg_manifest.json').write_text(json.dumps(record,ensure_ascii=False,indent=2),encoding='utf-8')
 write()
 try:
  # Inherits parent's redirected stdout; hidden on Windows, logged in the GUI.
  subprocess.run(args,check=True)
  csvpath=prefix.with_suffix('.csv');new=read_positions(csvpath)
  if 'Cz' not in new:raise ValueError('Official command did not output Cz')
  residuals={k:project(v,tri,p)[1] for k,p in new.items()}
  if max(residuals.values())>3:raise ValueError('Recomputed positions exceed 3 mm from the surface; inspect the results.')
  with open(out/'EEG_coordinate_changes.csv','w',newline='',encoding='utf-8-sig') as f:
   writer=csv.writer(f);writer.writerow(['name','old_x','old_y','old_z','new_x','new_y','new_z','dx_mm','dy_mm','dz_mm','displacement_mm'])
   for name,p in new.items():
    old=points.get(name);writer.writerow([name,*(['','',''] if old is None else old),*p,*(['','','',''] if old is None else [*(p-old),float(np.linalg.norm(p-old))])])
  record.update(status='COMPUTED_REQUIRES_VISUAL_REVIEW',point_count=len(new),Cz_RAS_mm=new['Cz'].tolist(),max_surface_residual_mm=max(residuals.values()))
  if 'Cz' in points:record['Cz_change_mm']=float(np.linalg.norm(new['Cz']-points['Cz']))
  write();print('Recomputation completed: '+str(csvpath)+'\nCz RAS mm: '+str(new['Cz'].tolist()),flush=True)
 except Exception as e:
  record.update(status='FAILED_DO_NOT_USE',error=str(e));write();raise
 return out

